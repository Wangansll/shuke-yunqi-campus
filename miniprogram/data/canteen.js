// 由档口数据实时算出，不手写数字，避免改数据忘了改文案
function countOf(halls) {
  return halls.map((h) => {
    const by = {}
    CAT_KEYS.forEach((c) => { by[c] = 0 })
    h.stalls.forEach((s) => { if (by[s.t] !== undefined) by[s.t] += 1 })
    const groups = CATS
      .filter((x) => by[x.c] > 0)
      .map((x) => ({ c: x.c, n: by[x.c], items: h.stalls.filter((s) => s.t === x.c).map((s) => s.n) }))
    return {
      id: h.id, name: h.name, short: h.short, area: h.area, score: h.score,
      total: h.stalls.length,
      top: h.stalls.slice(0, 2).map((s) => s.n).join(' · '),
      groups,
      by,
    }
  })
}

const STAT = countOf(HALLS)
const MAX_TOTAL = Math.max.apply(null, STAT.map((x) => x.total))
// 档口最多的那个食堂，进度条的刻度就是它
const MAX_HALL = STAT.reduce((a, b) => (b.total > a.total ? b : a), STAT[0])

// 补上「占最大值的百分比」，模板里直接算会踩 WXML 不支持方法的坑
const CARDS = STAT.map((x) => Object.assign({}, x, {
  pct: Math.round((x.total / MAX_TOTAL) * 100),
}))

// 横向对比：同一品类在各食堂各有几家
